// reportBucket is the width of each bucket in the per-scenario time-bucketed table.
const reportBucket = 10 * time.Second

// resultsReport renders a simulation results set as a Markdown report.
type resultsReport struct {
	results scenarioResults
}

func newResultsReport(r scenarioResults) *resultsReport {
	return &resultsReport{results: r}
}

func (rr *resultsReport) generateJSON() ([]byte, error) {
	type clientResults struct {
		Attempts int `json:"attempts"`
		Passes   int `json:"passes"`
	}
	type windowSuccess struct {
		Name        string        `json:"name"`
		FromSeconds float64       `json:"from_seconds"`
		ToSeconds   float64       `json:"to_seconds"`
		Wgo         clientResults `json:"wgo"`
		Kgo         clientResults `json:"kgo"`
	}
	type scenarioSuccess struct {
		Scenario          string                 `json:"scenario"`
		StaleFallback     *staleFallbackEvidence `json:"stale_fallback,omitempty"`
		Wgo               clientResults          `json:"wgo"`
		Kgo               clientResults          `json:"kgo"`
		Failures          []string               `json:"failures,omitempty"`
		Windows           []windowSuccess        `json:"windows,omitempty"`
		WgoInjectedDelays map[int32]int64        `json:"wgo_injected_delay_selections,omitempty"`
		KgoInjectedDelays map[int32]int64        `json:"kgo_injected_delay_selections,omitempty"`
	}
	results := make([]scenarioSuccess, 0, len(rr.results.entries))
	for _, res := range rr.results.entries {
		entry := scenarioSuccess{
			Scenario:          res.sc.name,
			StaleFallback:     res.staleFallback,
			WgoInjectedDelays: res.wgoLatencySelections, KgoInjectedDelays: res.kgoLatencySelections,
			Wgo: clientResults{Attempts: res.wgoSummary.total, Passes: res.wgoSummary.successes},
			Kgo: clientResults{Attempts: res.kgoSummary.total, Passes: res.kgoSummary.successes},
		}
		for _, window := range res.windows {
			entry.Windows = append(entry.Windows, windowSuccess{Name: window.window.name, FromSeconds: window.window.from.Seconds(), ToSeconds: window.window.to.Seconds(), Wgo: clientResults{Attempts: window.wgo.total, Passes: window.wgo.successes}, Kgo: clientResults{Attempts: window.kgo.total, Passes: window.kgo.successes}})
		}
		for _, failure := range checkResult(res) {
			entry.Failures = append(entry.Failures, failure.detail)
		}
		results = append(results, entry)
	}
	slices.SortFunc(results, func(a, b scenarioSuccess) int { return cmp.Compare(a.Scenario, b.Scenario) })
	data, err := json.MarshalIndent(results, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}

// generateMarkdown renders the full comparison report.
func (rr *resultsReport) generateMarkdown() string {
	var b strings.Builder
	title, command := "wgo vs kgo simulation report", "simulation"
	if len(rr.results.entries) > 0 && rr.results.entries[0].workloadDescription != "" {
		title, command = "Mimir distributor simulation report", "simulation-mimir"
	}
	fmt.Fprintf(&b, "# %s\n\n_Generated by `make %s`. Non-deterministic snapshot: latencies are real wall-clock, so the exact numbers vary between runs._\n\n", title, command)
	b.WriteString("> **Run-to-run variance:** Results below 100% success can vary because of randomness and wall-clock timing during testing. " +
		"The same code can produce 110/120 successful writes in one run and 80/120 in another.\n\n")
	brokers, partitions, spacing := clusterSize, clusterSize, eventSpacing
	if len(rr.results.entries) > 0 {
		brokers, partitions = rr.results.entries[0].sc.topology()
		spacing = rr.results.entries[0].sc.spacing()
	}
	if brokers == partitions {
		fmt.Fprintf(&b, "- Cluster: %d brokers / %d partitions (1:1)\n", brokers, partitions)
	} else {
		fmt.Fprintf(&b, "- Cluster: %d brokers / %d partitions\n", brokers, partitions)
	}
	fmt.Fprintf(&b, "- Warmup %s, observed duration shown per scenario, event spacing %s, app-request timeout %s\n",
		warmupDuration, spacing, appRequestTimeout)
	if command == "simulation-mimir" {
		fmt.Fprintf(&b, "- **Event**: one remote-write application event, issued every %s, recorded as a single success/failure when all its HTTP requests finish or the %s app-request timeout expires.\n\n", spacing, appRequestTimeout)
	} else {
		fmt.Fprintf(&b, "- **Event**: one simulated application write, issued every %s. Each event fans "+
			"out one Produce record per partition (%d records/event, one per broker since partitions and "+
			"brokers are 1:1) and is recorded as a single success/failure once every partition's record has "+
			"settled or the %s app-request timeout has elapsed.\n\n", eventSpacing, clusterSize, appRequestTimeout)

	}

	if len(rr.results.entries) > 0 && rr.results.entries[0].workloadDescription != "" {
		b.WriteString(rr.results.entries[0].workloadDescription + "\n\n")
		b.WriteString(rr.results.entries[0].workloadConfiguration + "\n\n")
	} else {
		rr.writeConfigSection(&b)
	}

	b.WriteString("Topology and workload configuration above describe the first scenario. Investigation cases list their own settings below.\n\n## Summary\n\n")
	b.WriteString("| Scenario | wgo success | kgo success | success Δ | wgo slow | wgo p99 | kgo p99 | hedge surge |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- | --- | --- |\n")
	for _, res := range rr.results.entries {
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %s |\n",
			res.sc.name,
			rr.appSuccessCell(res.wgoSummary), rr.appSuccessCell(res.kgoSummary),
			rr.successDeltaCell(res), rr.slowFractionCell(res),
			rr.formatDuration(res.wgoSummary.p99Latency), rr.formatDuration(res.kgoSummary.p99Latency),
			rr.hedgeSurgePct(res.totalPrimary, res.totalHedge))
	}
	b.WriteString("\n")

	for _, res := range rr.results.entries {
		rr.writeScenarioSection(&b, res)
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// Include settings so readers can distinguish scenario effects from client
// configuration differences.
func (rr *resultsReport) writeConfigSection(b *strings.Builder) {
	b.WriteString("## Client configuration\n\n")
	b.WriteString("Shared by both clients:\n\n")
	b.WriteString("| Setting | Value |\n| --- | --- |\n")
	fmt.Fprintf(b, "| Dial timeout | %s |\n", clientDialTimeout)
	fmt.Fprintf(b, "| Write / delivery timeout | %s |\n", clientWriteTimeout)
	fmt.Fprintf(b, "| Produce request timeout (+ overhead) | %s (+%s) |\n", clientProduceRequestTimeout, clientRequestTimeoutOverhead)
	fmt.Fprintf(b, "| Linger | %s |\n", clientLinger)
	fmt.Fprintf(b, "| Batch max bytes | %s |\n", commaInt(clientBatchMaxBytes))
	fmt.Fprintf(b, "| Metadata refresh interval | %s |\n", clientMetadataRefresh)
	b.WriteString("\n")

	b.WriteString("wgo-only — this simulation's own values, shown against `pkg/wgo`'s library " +
		"defaults for comparison (a value need not match its default; it's what this run actually " +
		"used):\n\n")
	b.WriteString("| Setting | Value | pkg/wgo default |\n| --- | --- | --- |\n")
	fmt.Fprintf(b, "| Hedger: min hedge delay | %s | %s |\n", wgoHedgerMinHedgeDelay, wgo.DefaultHedgerMinHedgeDelay)
	fmt.Fprintf(b, "| Hedger: max hedge agents | %d | %d |\n", wgoHedgerMaxHedgeAgents, wgo.DefaultHedgerMaxHedgeAgents)
	fmt.Fprintf(b, "| Demoter: probe interval | %s | %s |\n", wgoDemoterProbeInterval, wgo.DefaultDemoterProbeInterval)
	fmt.Fprintf(b, "| Cluster stats TTL | %s | %s |\n", wgoClusterStatsTTL, wgo.DefaultClusterStatsTTL)
	fmt.Fprintf(b, "| Health check: slow multiplier | %.1fx | %.1fx |\n", wgoHealthCheckSlowMultiplier, wgo.DefaultHealthCheckSlowMultiplier)
	fmt.Fprintf(b, "| Health check: max slow fraction | %.0f%% | %.0f%% |\n", 100*wgoHealthCheckMaxSlowFraction, 100*wgo.DefaultHealthCheckMaxSlowFraction)
	fmt.Fprintf(b, "| Health check: faulty threshold | %.0f%% | %.0f%% |\n", 100*wgoHealthCheckFaultyThreshold, 100*wgo.DefaultHealthCheckFaultyThreshold)
	fmt.Fprintf(b, "| Health check: max faulty fraction | %.0f%% | %.0f%% |\n", 100*wgoHealthCheckMaxFaultyFraction, 100*wgo.DefaultHealthCheckMaxFaultyFraction)
	b.WriteString("\n")

	b.WriteString("kgo-only:\n\n")
	b.WriteString("| Setting | Value |\n| --- | --- |\n")
	b.WriteString("| Partitioner | Manual — fixed leader per partition, never reroutes |\n")
	fmt.Fprintf(b, "| Max produce requests in-flight per broker | %d |\n", clientMaxInflight)
	b.WriteString("| Record retries | unlimited (bounded only by the delivery timeout above) |\n")
	b.WriteString("| Retry backoff | 250ms exponential, capped at 5s, without jitter |\n")
	b.WriteString("| Max buffered records / bytes | unlimited |\n")
	b.WriteString("\n")
}

func (rr *resultsReport) writeScenarioSection(b *strings.Builder, res scenarioResult) {
	fmt.Fprintf(b, "## %s\n\n%s\n\n", res.sc.name, res.sc.description)
	if res.sc.profile != nil {
		brokers, partitions := res.sc.topology()
		fmt.Fprintf(b, "Scenario topology: %d agents, %d primary partitions, %d secondary partitions.\n\n", brokers, partitions, res.sc.profile.secondaryPartitions)
		if res.workloadDescription != "" {
			fmt.Fprintf(b, "%s\n\n%s\n\n", res.workloadDescription, res.workloadConfiguration)
		}
	}
	if evidence := res.staleFallback; evidence != nil {
		fmt.Fprintf(b, "Discovery-skew evidence: %d broker-only withdrawals; %d stale topic-discovery responses; %d fallback wire errors; %d successful cascades with at least three attempts; %d terminal errors.\n\n", evidence.BrokerOnlyWithdrawals, evidence.StaleRoutingResponses, evidence.FallbackErrors, evidence.ThirdAttemptSuccesses, evidence.TerminalErrors)
	}
	if len(res.wgoLatencySelections)+len(res.kgoLatencySelections) > 0 {
		fmt.Fprintf(b, "Produce responses selected for injected delay (not necessarily delivered before cancellation): wgo %v; kgo %v.\n\n", res.wgoLatencySelections, res.kgoLatencySelections)
	}

	fmt.Fprintf(b, "- observed duration: %s; event spacing: %s\n", res.sc.duration(), res.sc.spacing())
	fmt.Fprintf(b, "- app requests (wgo): %s\n", rr.summaryLine(res.wgoSummary))
	fmt.Fprintf(b, "- app requests (kgo): %s\n", rr.summaryLine(res.kgoSummary))
	fmt.Fprintf(b, "- wgo-kgo success delta: %s\n", rr.successDeltaLine(res))
	if line := rr.slowFractionLine(res); line != "" {
		fmt.Fprintf(b, "- %s\n", line)
	}
	if len(res.sc.transportPhases) > 0 {
		for _, phase := range res.sc.transportPhases {
			if phase.action == withdrawPod {
				fmt.Fprintf(b, "- Metadata responses naming withdrawn broker %d as leader: wgo %d, kgo %d\n", phase.nodeID, res.wgoMissingLeaders[phase.nodeID], res.kgoMissingLeaders[phase.nodeID])
			}
		}
		fmt.Fprintf(b, "- transport faults: wgo %d closed connections, %d refused dials, %d dropped bytes; kgo %d closed connections, %d refused dials, %d dropped bytes\n", res.wgoTransport.closedConnections, res.wgoTransport.rejectedDials, res.wgoTransport.droppedBytes, res.kgoTransport.closedConnections, res.kgoTransport.rejectedDials, res.kgoTransport.droppedBytes)
		description := res.recoveryResponseDescription
		if description == "" {
			description = "successful wgo Produce responses (including probes)"
		}
		for _, nodeID := range slices.Sorted(maps.Keys(res.wgoTransport.recoveredResponses)) {
			fmt.Fprintf(b, "- %s from restored broker %d during recovery: %d\n", description, nodeID, res.wgoTransport.recoveredResponses[nodeID])
		}
	}
	if res.sc.expect.recoveryFrom != nil {
		fmt.Fprintf(b, "- recovery scheduled from %s: %s, p99 %s", *res.sc.expect.recoveryFrom, rr.appSuccessCell(res.wgoRecovery), rr.formatDuration(res.wgoRecovery.p99Latency))
		if res.sc.expect.slowBudget != nil {
			fmt.Fprintf(b, "; every recovery event must finish within %s", *res.sc.expect.slowBudget)
		}
		b.WriteByte('\n')
	}
	if res.sc.expect.maxHedgeSurge != nil {
		fmt.Fprintf(b, "- maximum hedge surge: %.0f%%\n", 100**res.sc.expect.maxHedgeSurge)
	}
	if res.totalPrimary > 0 {
		fmt.Fprintf(b, "- hedge surge: %d primary + %d hedge attempts (%s extra; excludes connection retries)\n",
			res.totalPrimary, res.totalHedge, rr.hedgeSurgePct(res.totalPrimary, res.totalHedge))
	}
	b.WriteString("\n")

	if len(res.windows) > 0 {
		b.WriteString("### Scheduled application windows\n\n| Window | Scheduled range | wgo success | kgo success | wgo mean | kgo mean | wgo p99 | kgo p99 |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n")
		for _, window := range res.windows {
			fmt.Fprintf(b, "| %s | %s–%s | %s | %s | %s | %s | %s | %s |\n", window.window.name, window.window.from, window.window.to, rr.appSuccessCell(window.wgo), rr.appSuccessCell(window.kgo), rr.formatDuration(window.wgo.meanLatency), rr.formatDuration(window.kgo.meanLatency), rr.formatDuration(window.wgo.p99Latency), rr.formatDuration(window.kgo.p99Latency))
		}
		b.WriteString("\n")
	}
	rr.writeBucketTable(b, res)
	rr.writeErrorTable(b, res)
	b.WriteString("\n")
}

func (rr *resultsReport) writeErrorTable(b *strings.Builder, res scenarioResult) {
	if len(res.wgoErrorCounts) == 0 && len(res.kgoErrorCounts) == 0 {
		return
	}

	seen := map[string]struct{}{}
	for e := range res.wgoErrorCounts {
		seen[e] = struct{}{}
	}
	for e := range res.kgoErrorCounts {
		seen[e] = struct{}{}
	}
	errs := slices.Sorted(maps.Keys(seen))

	b.WriteString("\n| error | wgo | kgo |\n| --- | --- | --- |\n")
	for _, e := range errs {
		fmt.Fprintf(b, "| %s | %s | %s |\n",
			e,
			rr.errorRatePct(res.wgoErrorCounts[e], res.wgoSummary.total),
			rr.errorRatePct(res.kgoErrorCounts[e], res.kgoSummary.total))
	}
}

func (rr *resultsReport) writeBucketTable(b *strings.Builder, res scenarioResult) {
	wgoBuckets := res.wgoBuckets
	kgoBuckets := res.kgoBuckets
	n := max(len(kgoBuckets), len(wgoBuckets))
	if n == 0 && len(res.produceDeltas) == 0 {
		b.WriteString("(no observations)\n")
		return
	}

	b.WriteString("| bucket | wgo success | wgo mean | wgo p99 | wgo surge (hedge/prim) | kgo success | kgo mean | kgo p99 |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- | --- | --- |\n")
	secs := int(reportBucket / time.Second)
	for i := range n {
		var wgo, kgo observationsSummary
		if i < len(wgoBuckets) {
			wgo = wgoBuckets[i]
		}
		if i < len(kgoBuckets) {
			kgo = kgoBuckets[i]
		}
		surge := "n/a"
		if i < len(res.produceDeltas) {
			surge = rr.bucketSurgeCell(res.produceDeltas[i])
		}
		fmt.Fprintf(b, "| %ds–%ds | %s | %s | %s | %s | %s | %s | %s |\n",
			i*secs, (i+1)*secs,
			rr.bucketSuccessCell(wgo), rr.formatDuration(wgo.meanLatency), rr.formatDuration(wgo.p99Latency),
			surge,
			rr.bucketSuccessCell(kgo), rr.formatDuration(kgo.meanLatency), rr.formatDuration(kgo.p99Latency))
	}
	if drain := len(res.produceDeltas) - n; drain > 0 {
		var d counterBucketDelta
		for _, x := range res.produceDeltas[n:] {
			d.primary += x.primary
			d.hedge += x.hedge
		}
		if d.primary != 0 || d.hedge != 0 {
			surge := rr.bucketSurgeCell(d)
			if d.primary == 0 {
				surge = fmt.Sprintf("%d/0 (n/a)", d.hedge)
			}
			fmt.Fprintf(b, "| %ds+ drain | — | — | — | %s | — | — | — |\n", n*secs, surge)
		}
	}
}

// formatDuration renders a duration with one decimal in seconds so cells are
// uniform width and easy to scan.
func (rr *resultsReport) formatDuration(d time.Duration) string {
	return fmt.Sprintf("%.1fs", d.Seconds())
}

// commaInt renders a non-negative n with thousands separators, e.g.
// "16,000,000", so large byte counts in the config table are easy to scan.
func commaInt(n int) string {
	s := strconv.Itoa(n)
	for i := len(s) - 3; i > 0; i -= 3 {
		s = s[:i] + "," + s[i:]
	}
	return s
}

// appSuccessCell renders an app-level success cell, e.g. "950/1000 (95.0%)".
func (rr *resultsReport) appSuccessCell(s observationsSummary) string {
	if s.total == 0 {
		return "n/a"
	}
	return fmt.Sprintf("%d/%d (%.1f%%)", s.successes, s.total, 100*float64(s.successes)/float64(s.total))
}

// summaryLine renders a one-line success/latency summary of a set of observations.
func (rr *resultsReport) summaryLine(s observationsSummary) string {
	rate := "n/a"
	if s.total > 0 {
		rate = fmt.Sprintf("%d/%d (%.1f%%)", s.successes, s.total, 100*float64(s.successes)/float64(s.total))
	}
	return fmt.Sprintf("success=%s mean=%s p50=%s p99=%s",
		rate, rr.formatDuration(s.meanLatency), rr.formatDuration(s.p50Latency), rr.formatDuration(s.p99Latency))
}

// successDeltaCell renders wgo's success-rate margin over kgo, e.g.
// "+45.0 pts". "n/a" when no minSuccessDeltaVsKgo gate is configured, so
// it's not mistaken for a gate passing with zero margin.
func (rr *resultsReport) successDeltaCell(res scenarioResult) string {
	if !res.hasSuccessDeltaGate() {
		return "n/a"
	}
	return fmt.Sprintf("%+.1f pts", 100*(res.successRate()-res.kgoSuccessRate()))
}

// successDeltaLine is the per-scenario bullet for the same delta, including
// the gate threshold when one is configured.
func (rr *resultsReport) successDeltaLine(res scenarioResult) string {
	cell := rr.successDeltaCell(res)
	if res.hasSuccessDeltaGate() {
		return fmt.Sprintf("%s (want ≥ %.1f pts)", cell, 100**res.sc.expect.minSuccessDeltaVsKgo)
	}
	return cell
}

// slowFractionCell renders wgo's measured slow fraction against its ceiling
// when the scenario asserts one, e.g. "8.2% (≤10.0% >2s)". "n/a" when the
// scenario has no slow-fraction gate — there is no budget to measure against.
func (rr *resultsReport) slowFractionCell(res scenarioResult) string {
	if !res.hasSlowFractionGate() {
		return "n/a"
	}
	return fmt.Sprintf("%.1f%% (≤%.1f%% >%s)",
		100**res.wgoSlowFraction, 100**res.sc.expect.maxWgoSlowFraction, *res.sc.expect.slowBudget)
}

// slowFractionLine is the per-scenario bullet for the same measurement.
func (rr *resultsReport) slowFractionLine(res scenarioResult) string {
	if !res.hasSlowFractionGate() {
		return ""
	}
	return fmt.Sprintf("wgo slow fraction: %.1f%% of requests slower than %s (ceiling %.1f%%)",
		100**res.wgoSlowFraction, *res.sc.expect.slowBudget, 100**res.sc.expect.maxWgoSlowFraction)
}

// hedgeSurgePct renders the overall hedge surge (hedge attempts as a
// percentage of primary), e.g. "+12.3%", or "n/a" when no primary requests were sent.
func (rr *resultsReport) hedgeSurgePct(primary, hedge int64) string {
	if primary <= 0 {
		return "n/a"
	}
	return fmt.Sprintf("+%.1f%%", 100*float64(hedge)/float64(primary))
}

// errorRatePct renders count as a percentage of total, e.g. "0.8%".
func (rr *resultsReport) errorRatePct(count, total int) string {
	if total == 0 {
		return "n/a"
	}
	return fmt.Sprintf("%.1f%%", 100*float64(count)/float64(total))
}

// bucketSuccessCell renders a per-bucket success cell, e.g. "20/20 (100%)".
func (rr *resultsReport) bucketSuccessCell(s observationsSummary) string {
	if s.total == 0 {
		return "n/a"
	}
	return fmt.Sprintf("%d/%d (%.0f%%)", s.successes, s.total, 100*float64(s.successes)/float64(s.total))
}

// bucketSurgeCell renders one bucket's hedge/primary cell, e.g. "12/200 (+6%)".
func (rr *resultsReport) bucketSurgeCell(d counterBucketDelta) string {
	if d.primary <= 0 {
		return "n/a"
	}
	return fmt.Sprintf("%d/%d (+%.0f%%)", d.hedge, d.primary, 100*float64(d.hedge)/float64(d.primary))
}
